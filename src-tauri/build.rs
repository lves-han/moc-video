fn main() {
    // FFmpeg dylibs ship in Contents/Frameworks (ADR-067); tauri-build adds that rpath for
    // the configured frameworks. Debug builds and tests also load them from the build
    // output; release binaries carry no local path.
    if std::env::var("CARGO_CFG_TARGET_FAMILY").as_deref() == Ok("unix")
        && std::env::var("PROFILE").as_deref() == Ok("debug")
        && let Ok(dir) = std::env::var("FFMPEG_DIR")
    {
        let lib = std::path::Path::new(&dir).join("lib");
        let lib = lib.canonicalize().unwrap_or(lib);
        println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
    }
    println!("cargo:rerun-if-env-changed=FFMPEG_DIR");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        // Private bundled libraries also satisfy each other's dependencies.
        println!("cargo:rustc-link-arg=-Wl,--disable-new-dtags,-rpath,$ORIGIN/../lib/moc-video");
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let sdk = std::env::var("FFMPEG_DIR").expect("prepare the FFmpeg SDK first");
        let output = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
        let profile = output.ancestors().nth(3).expect("Cargo profile directory");
        for name in [
            "avcodec-63.dll",
            "avformat-63.dll",
            "avutil-61.dll",
            "swresample-7.dll",
        ] {
            let source = std::path::Path::new(&sdk).join("bin").join(name);
            println!("cargo:rerun-if-changed={}", source.display());
            for directory in [profile.to_path_buf(), profile.join("deps")] {
                std::fs::create_dir_all(&directory).expect("create runtime directory");
                std::fs::copy(&source, directory.join(name)).expect("copy FFmpeg runtime DLL");
            }
        }
        let manifest =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/windows.manifest");
        println!("cargo:rerun-if-changed={}", manifest.display());
        println!("cargo:rustc-link-arg-tests=/MANIFEST:EMBED");
        println!(
            "cargo:rustc-link-arg-tests=/MANIFESTINPUT:{}",
            manifest.display()
        );
    }
    // Autogenerated app permissions live across feature builds. Remove only the
    // test command's derived file when returning to a production build.
    if std::env::var_os("CARGO_FEATURE_T01_AUTOMATION").is_none() {
        let test_permission = std::path::Path::new("permissions/autogenerated/t01_control.toml");
        if test_permission.exists() {
            std::fs::remove_file(test_permission).expect("remove stale test-only permission");
        }
    }
    const COMMANDS: &[&str] = &[
        "player_fullscreen",
        "runtime_status",
        "runtime_prepare",
        "get_sources",
        "sync_catalog",
        "get_home",
        "get_details",
        "resolve_episode",
        "start_line_round",
        "get_line_round",
        "confirm_line_candidate",
        "cancel_line_round",
        "play_line",
        "refresh_line",
        "report_line_playback",
        "open_playback",
        "close_playback",
        "cancel_request",
        "start_interaction",
        "finish_interaction",
        "get_settings",
        "save_settings",
        "get_resource_status",
        "release_resolution",
        "match_playback",
        "list_history",
        "save_history",
        "remove_history",
        "clear_history",
        "get_media_cache",
        "clear_media_cache",
        "list_watchlist",
        "add_watchlist",
        "remove_watchlist",
        "search_catalog",
        "get_live_channels",
        "open_live",
        "list_local_videos",
        "open_local",
        "app_close_started",
        "app_close_aborted",
        "app_close_ready",
        "window_bounds_now",
        "app_reset",
        "app_reset_recovery",
        "app_service_import",
        "app_service_delete",
        "app_playback_sources",
        #[cfg(feature = "t01-automation")]
        "t01_control",
    ];
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS))
            .codegen(tauri_build::CodegenContext::new()),
    )
    .expect("Tauri configuration and permission generation failed");
}
