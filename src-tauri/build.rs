fn main() {
    // FFmpeg dylibs ship in Contents/Frameworks (ADR-067); tauri-build adds that rpath for
    // the configured frameworks. Debug builds and tests also load them from the build
    // output; release binaries carry no local path.
    if std::env::var("PROFILE").as_deref() == Ok("debug")
        && let Ok(dir) = std::env::var("FFMPEG_DIR")
    {
        let lib = std::path::Path::new(&dir).join("lib");
        let lib = lib.canonicalize().unwrap_or(lib);
        println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
    }
    println!("cargo:rerun-if-env-changed=FFMPEG_DIR");
    // Autogenerated app permissions live across feature builds. Remove only the
    // test command's derived file when returning to a production build.
    if std::env::var_os("CARGO_FEATURE_T01_AUTOMATION").is_none() {
        let test_permission = std::path::Path::new("permissions/autogenerated/t01_control.toml");
        if test_permission.exists() {
            std::fs::remove_file(test_permission).expect("remove stale test-only permission");
        }
    }
    const COMMANDS: &[&str] = &[
        "player_fullscreen",
        "runtime_status",
        "runtime_prepare",
        "get_sources",
        "sync_catalog",
        "get_home",
        "get_details",
        "resolve_episode",
        "open_playback",
        "close_playback",
        "cancel_request",
        "start_interaction",
        "finish_interaction",
        "get_settings",
        "save_settings",
        "get_resource_status",
        "release_resolution",
        "match_playback",
        "list_history",
        "save_history",
        "remove_history",
        "clear_history",
        "get_media_cache",
        "clear_media_cache",
        "list_watchlist",
        "add_watchlist",
        "remove_watchlist",
        "search_catalog",
        "get_live_channels",
        "open_live",
        "list_local_videos",
        "open_local",
        "app_close_started",
        "app_close_aborted",
        "app_close_ready",
        "window_bounds_now",
        #[cfg(feature = "t01-automation")]
        "t01_control",
    ];
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS))
            .codegen(tauri_build::CodegenContext::new()),
    )
    .expect("Tauri configuration and permission generation failed");
}
