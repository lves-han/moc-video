"""Deterministic DTO types from the working app and bridge schemas."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate():
    app = json.loads((ROOT / "protocol/app.schema.json").read_text(encoding="utf-8"))
    bridge = json.loads((ROOT / "protocol/bridge.openapi.json").read_text(encoding="utf-8"))

    def translate(schema, owner):
        if schema is True:
            return "unknown"
        if schema is False:
            return "never"
        if "$ref" in schema:
            ref = schema["$ref"]
            name = ref.rsplit("/", 1)[-1]
            return ("Bridge_" if "bridge.openapi.json" in ref or (owner == "bridge" and ref.startswith("#")) else "") + name
        if "const" in schema:
            return json.dumps(schema["const"], ensure_ascii=False)
        if "enum" in schema:
            return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
        for union in ("oneOf", "anyOf"):
            if union in schema:
                return "(" + " | ".join(translate(value, owner) for value in schema[union]) + ")"
        kind = schema.get("type")
        if isinstance(kind, list):
            return "(" + " | ".join(translate({**schema, "type": value}, owner) for value in kind) + ")"
        if kind == "array":
            return "Array<" + translate(schema.get("items", True), owner) + ">"
        if kind == "object" or "properties" in schema:
            required = schema.get("required", [])
            fields = [json.dumps(name) + ("" if name in required else "?") + ": " + translate(value, owner)
                      for name, value in schema.get("properties", {}).items()]
            additional = schema.get("additionalProperties", True)
            if additional is not False:
                fields.append("[key: string]: " + translate(additional, owner))
            result = "{ " + "; ".join(fields) + " }"
        elif kind in ("string", "boolean", "null"):
            result = kind
        elif kind in ("number", "integer"):
            result = "number"
        else:
            result = "unknown"
        if "allOf" in schema:
            parts = [translate(part, owner) for part in schema["allOf"] if "if" not in part]
            if parts:
                result = "(" + " & ".join(([result] if result != "unknown" else []) + parts) + ")"
        return result

    lines = ["// Generated by tests/acceptance/t05_models.py from protocol/. Do not edit by hand."]
    for name, schema in bridge["components"]["schemas"].items():
        lines.append(f"export type Bridge_{name} = {translate(schema, 'bridge')};")
    for name, schema in app["$defs"].items():
        lines.append(f"export type {name} = {translate(schema, 'app')};")
    for title, prefix in (("CommandArgs", "Args_"), ("CommandResults", "Result_")):
        lines.append("export type " + title + " = {")
        lines.extend(f'  "{name}": {prefix}{name};' for name in app["x-command-contracts"])
        lines.append("};")
    lines.extend([
        "export type Command = keyof CommandArgs;",
        "export type CommandInput<C extends Command> = CommandArgs[C]['input'];",
        "export type CommandData<C extends Command> = Extract<CommandResults[C], {data: unknown}>['data'];",
        "export const REQUEST_BUDGETS = " + json.dumps(app["x-request-budgets"], ensure_ascii=False) + " as const;",
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "src/models.ts").write_text(generate(), encoding="utf-8")
